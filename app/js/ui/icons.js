function icon(name, { size = 20, className = "" } = {}) {
  const body = PATHS[name] || PATHS.rss;
  return (
    `<svg class="icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ` +
    `aria-hidden="true" focusable="false">${body}</svg>`
  );
}

export function iconEl(name, opts) {
  const t = document.createElement("template");
  t.innerHTML = icon(name, opts);
  return t.content.firstElementChild;
}

// A feed's own icon when it has one, otherwise the generic feed symbol.
export function feedIconEl(feed, size = 20) {
  if (!feed.icon) return iconEl("rss", { size });
  const img = document.createElement("img");
  Object.assign(img, { className: "feed-icon", src: feed.icon, alt: "", width: size, height: size });
  return img;
}

// Replaces every <span data-icon="..."> placeholder with its SVG.
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    el.replaceWith(iconEl(el.dataset.icon, { size: Number(el.dataset.size) || 20 }));
  }
}